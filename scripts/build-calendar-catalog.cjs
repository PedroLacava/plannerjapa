// Generate from the planner's own definitions so the feed follows future edits.
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('public/planner.html', 'utf8');
const start = html.indexOf('var TOUR_DEFS = {');
const end = html.indexOf('window.JaplannerPokemon.register(TOUR_DEFS);', start);
if (start < 0 || end < start) throw Error('Planner catalogue boundaries not found');
const context = { window: {}, document: { addEventListener() {} } };
vm.createContext(context);
vm.runInContext(fs.readFileSync('public/pokemon-view.js', 'utf8'), context, { timeout: 1000 });
vm.runInContext(html.slice(start, end) + 'window.JaplannerPokemon.register(TOUR_DEFS);', context, { timeout: 1000 });
const tours = {};
for (const [id, def] of Object.entries(context.TOUR_DEFS)) {
  tours[id] = { label: def.label, hours: def.hours, region: def.region, bullets: def.bullets, suggested: def.suggested, travel: def.travel, guide: def.guide ? { city: def.guide.city, timeMode: def.guide.timeMode, smartRoute: def.guide.smartRoute } : undefined };
}
fs.writeFileSync('src/lib/calendar-catalog.ts', '// Generated by scripts/build-calendar-catalog.cjs. Do not edit.\nexport default ' + JSON.stringify(tours, null, 2) + ';\n');
console.log('Calendar catalogue:', Object.keys(tours).length, 'activities');
